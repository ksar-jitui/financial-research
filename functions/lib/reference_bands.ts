// 分组带的意义：银行/保险/证券的经营现金流由客户存贷款与同业往来主导，
// 与实体企业放在同一分布里比会互相污染，所以两类各自定带。
// 跑批脚本用同一个正则分组，改这里必须一起改，否则参照带与实测分布对不上。
export const FINANCIAL_ORG = /银行|保险|证券|金融|信托|租赁/;
// 组内观测太少时分位数不稳，退回全市场带。
const MIN_GROUP_OBSERVATIONS = 300;

export type BandGroup = {
  key: string;
  label: string;
  n: number;
  level: [number, number][];
  change: [number, number][];
  // 带的层级：行业一级板块 → 实体/金融 → 全市场。判定与展示都要说明用的是哪一层，
  // 因为同一分数在不同池里的含义并不相同。
  kind: "industry" | "org" | "market" | "none";
};

const EMPTY_GROUP: BandGroup = {
  key: "未标定",
  label: "参照分布未生成",
  n: 0,
  level: [],
  change: [],
  kind: "none",
};

function usable(candidate: any): boolean {
  return Boolean(candidate && candidate.n >= MIN_GROUP_OBSERVATIONS && candidate.level?.length);
}

export function bandGroupFor(orgType: string): BandGroup {
  const groups = REFERENCE.groups ?? {};
  const wanted = FINANCIAL_ORG.test(orgType ?? "") ? "金融" : "实体";
  if (usable(groups[wanted])) return { ...groups[wanted], kind: "org" };
  if (usable(groups["全市场"])) return { ...groups["全市场"], kind: "market" };
  // 参照表还没生成或被清空：如实返回空网格，让分位定位给出 null，
  // 判定环节据此标成「未标定」而不是拿 0 分位冒充结论。
  return EMPTY_GROUP;
}

// 行业优先：同一年度降幅，在板块普跌与板块独跌两种语境下性质完全不同，
// 所以只要该一级板块的观测数够建带，就必须在板块内定位，而不是混在全市场里比。
export function bandFor(industryName: string, orgType: string): BandGroup {
  const industries = REFERENCE.industries ?? {};
  const chosen = industries[industryName];
  if (usable(chosen)) return { ...chosen, label: `${chosen.key}（一级板块）`, kind: "industry" };
  return bandGroupFor(orgType);
}

// 「优质档」与「规模」要靠行业内的毛利率/净利率/营收分布，取不到行业带时一律为 null，
// 不拿全市场分布冒充行业前 5%——那是两个完全不同的命题。
export function industryContext(industryName: string) {
  const g = (REFERENCE.industries ?? {})[industryName];
  if (!usable(g)) return null;
  return g;
}

// 分位数网格是断点表，不是完整样本；落在两个断点之间就线性插值。
export function percentileIn(value: number, grid: [number, number][]): number | null {
  if (!Array.isArray(grid) || grid.length === 0) return null;
  if (!Number.isFinite(value)) return null;
  if (value <= grid[0][1]) return grid[0][0];
  const last = grid[grid.length - 1];
  if (value >= last[1]) return last[0];
  for (let i = 0; i < grid.length - 1; i++) {
    const [p0, v0] = grid[i];
    const [p1, v1] = grid[i + 1];
    if (value < v1) {
      if (v1 === v0) return p1;
      return Math.round((p0 + ((value - v0) / (v1 - v0)) * (p1 - p0)) * 10) / 10;
    }
  }
  return last[0];
}
